def init_db():
    conn = sqlite3.connect("quiz_results.db")
    c = conn.cursor()
    c.execute('''CREATE TABLE IF NOT EXISTS results 
                 (student_name TEXT, 
                  student_email TEXT, 
                  quiz_type TEXT, 
                  difficulty TEXT, 
                  score INTEGER, 
                  total INTEGER,
                  percentage REAL,
                  date TEXT)''')
    
    c.execute("PRAGMA table_info(results)")
    columns = [col[1] for col in c.fetchall()]
    
    if "course_name" not in columns:
        c.execute("ALTER TABLE results ADD COLUMN course_name TEXT DEFAULT 'General AI'")
    if "language" not in columns:
        c.execute("ALTER TABLE results ADD COLUMN language TEXT DEFAULT 'English'")
        
    conn.commit()
    conn.close()

def save_result(name, email, course, lang, quiz_type, difficulty, score, total, percentage):
    init_db()
    conn = sqlite3.connect("quiz_results.db")
    c = conn.cursor()
    current_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    c.execute("INSERT INTO results (student_name, student_email, course_name, language, quiz_type, difficulty, score, total, percentage, date) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)", 
              (name, email, course, lang, quiz_type, difficulty, score, total, percentage, current_time))
    conn.commit()
    conn.close()

def get_all_results():
    init_db()
    conn = sqlite3.connect("quiz_results.db")
    c = conn.cursor()
    try:
        c.execute("SELECT student_name, student_email, course_name, language, quiz_type, difficulty, score, total, percentage, date FROM results")
        data = c.fetchall()
    except sqlite3.OperationalError:
        data = []
    conn.close()
    return data

