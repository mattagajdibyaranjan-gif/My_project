def generate_advanced_quiz(course_name, count, quiz_type, difficulty, lang):
    topic = course_name.strip() if course_name.strip() else "Python"
    
    odia_pool = [
        {
            "q": f"[{quiz_type}] {topic} ର ଏକ Complex System ରେ Memory Leak ରୋକିବା ପାଇଁ custom garbage collection trigger ସମୟରେ କେଉଁ decorator/dunder method ବ୍ୟବହାର ହୁଏ?",
            "options": ["__del__ ଏବଂ gc.collect()", "__init__ ଏବଂ malloc()", "__exit__ ଏବଂ free()", "__dealloc__ ଏବଂ clear()"],
            "answer": "__del__ ଏବଂ gc.collect()"
        },
        {
            "q": f"[{quiz_type}] High Concurrency Multithreading Application ରେ {topic} GIL କୁ bypass କରିବା ପାଇଁ ସବୁଠାରୁ ଉପଯୁକ୍ତ architecture କେଉଁଟି?",
            "options": ["Multiprocessing Module", "Threading Module", "Asyncio Event Loop", "Coroutines"],
            "answer": "Multiprocessing Module"
        }
    ]

    english_pool = [
        {
            "q": f"[{quiz_type} - {difficulty}] In a high-throughput {topic} backend, how do you completely bypass the GIL (Global Interpreter Lock)?",
            "options": ["Utilize the `multiprocessing` module", "Apply `threading.Thread` with mutex", "Implement `asyncio` event loops", "Use context managers"],
            "answer": "Utilize the `multiprocessing` module"
        },
        {
            "q": f"[{quiz_type} - {difficulty}] In {topic} architecture, what is the exact execution order during class instantiation when metaclasses are involved?",
            "options": ["__new__ -> __init__ -> __call__", "__init__ -> __new__", "__call__ -> __init__", "__prepare__ -> __new__ -> __init__"],
            "answer": "__prepare__ -> __new__ -> __init__"
        }
    ]

    hindi_pool = [
        {
            "q": f"[{quiz_type}] {topic} में Concurrency और GIL Constraints को बायपास करने के लिए सबसे बेहतर समाधान क्या है?",
            "options": ["Multiprocessing मॉड्यूल का उपयोग", "Threading तकनीक", "Asyncio कॉलबैक", "ग्लोबल वेरिएबल लॉकिंग"],
            "answer": "Multiprocessing मॉड्यूल का उपयोग"
        }
    ]

    if lang == "Odia":
        pool = odia_pool
    elif lang == "Hindi":
        pool = hindi_pool
    else:
        pool = english_pool

    shuffled_pool = pool.copy()
    random.shuffle(shuffled_pool)

    questions = []
    for i in range(count):
        if i < len(shuffled_pool):
            questions.append(shuffled_pool[i])
        else:
            questions.append({
                "q": f"[{quiz_type} - {difficulty}] Q{i+1}: What is the primary optimization mechanism in {topic} module #{i+1}?",
                "options": [f"Strategy A: Memory Pooling #{i+1}", f"Strategy B: Lock Free Queues", f"Strategy C: Zero-Copy Serialization", f"Strategy D: JIT Compilation"],
                "answer": f"Strategy A: Memory Pooling #{i+1}"
            })

    return questions

